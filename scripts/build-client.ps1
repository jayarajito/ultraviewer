# JustKeepRemote — build the RustDesk (Flutter) Windows client from source.
# Prereqs: scripts/install-deps.ps1 completed (vcpkg static deps present).
# Produces: vendor/rustdesk/flutter/build/windows/x64/runner/Release/rustdesk.exe
#
# Steps:
#   1. assemble build env (VS DevShell + vcpkg + libclang + NASM)
#   2. flutter pub get (fetch Dart deps)
#   3. python build.py --flutter --hwcodec --skip-portable-pack
#      (cargo build --release of librustdesk.dll, then flutter build windows)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
. (Join-Path $PSScriptRoot 'env.ps1')

$rustdesk = Join-Path $repo 'vendor\rustdesk'
Set-Location $rustdesk

# Remove any stale Flutter Windows build cache. A CMakeCache.txt generated by a
# different VS generator (e.g. from the global Flutter 3.47.8) makes 3.24.5 fail
# with "generator does not match". Nuke flutter/build so CMake regenerates clean.
$flutterBuild = Join-Path $rustdesk 'flutter\build'
if (Test-Path $flutterBuild) {
    Write-Host "=== removing stale flutter/build cache ===" -ForegroundColor Cyan
    Remove-Item $flutterBuild -Recurse -Force -ErrorAction SilentlyContinue
}

Write-Host "=== flutter pub get ===" -ForegroundColor Cyan
Push-Location (Join-Path $rustdesk 'flutter')
flutter pub get
$pg = $LASTEXITCODE
Pop-Location
if ($pg -ne 0) { Write-Host "flutter pub get FAILED ($pg)" -ForegroundColor Red; exit $pg }

Write-Host "=== python build.py --flutter --hwcodec --skip-portable-pack ===" -ForegroundColor Cyan
python build.py --flutter --hwcodec --skip-portable-pack
$code = $LASTEXITCODE

$exe = Join-Path $rustdesk 'flutter\build\windows\x64\runner\Release\rustdesk.exe'
if (Test-Path $exe) {
    Write-Host "BUILD OK -> $exe" -ForegroundColor Green
} else {
    Write-Host "build.py exit=$code; rustdesk.exe not found yet." -ForegroundColor Yellow
}
exit $code
